package net.terrainstudio.test;

import net.mcreator.plugin.JavaPlugin;
import net.mcreator.plugin.Plugin;
import net.mcreator.plugin.events.PreGeneratorsLoadingEvent;
import net.mcreator.generator.Generator;
import net.mcreator.generator.setup.WorkspaceGeneratorSetup;
import net.mcreator.workspace.Workspace;
import net.mcreator.workspace.WorkspaceUtils;
import net.mcreator.workspace.settings.WorkspaceSettings;
import net.terrainstudio.TerrainCompiler;
import net.terrainstudio.WorkspaceInstaller;
import java.nio.file.*;

/** Test-only isolated MCreator workspace bootstrap; never packaged in the product plugin. */
public class WorkspaceTestPlugin extends JavaPlugin {
    public WorkspaceTestPlugin(Plugin plugin) {
        super(plugin);
        addListener(PreGeneratorsLoadingEvent.class, event -> {
            Thread thread = new Thread(() -> {
                try {
                    String generator = "neoforge-26.1.2";
                    while (!Generator.GENERATOR_CACHE.containsKey(generator)) Thread.sleep(100);
                    Path root = Path.of(System.getenv("TERRAIN_TEST_WORKSPACE"));
                    WorkspaceSettings settings = new WorkspaceSettings("terrain_test");
                    settings.setVersion("1.0.0"); settings.setModName("Terrain Test"); settings.setDescription("Disposable integration test");
                    settings.setAuthor("Test"); settings.setLicense("Not specified"); settings.setWebsiteURL("https://mcreator.net/");
                    settings.setUpdateURL(""); settings.setCurrentGenerator(generator);
                    Workspace workspace = Workspace.createWorkspace(root.resolve("terrain_test.mcreator").toFile(), settings);
                    WorkspaceGeneratorSetup.setupWorkspaceBase(workspace);
                    workspace.getGenerator().generateBase(false);
                    WorkspaceInstaller.install(root, TerrainCompiler.compile(Files.readString(Path.of(System.getenv("TERRAIN_TEST_PROJECT"))), "terrain_test", generator));
                    WorkspaceUtils.removeAutoGeneratedCode(workspace, null);
                    workspace.getGenerator().generateBase(false);
                    if (!Files.isRegularFile(root.resolve("src/main/java/net/terrainstudio/generated/TerrainStudioWorldgen.java")) ||
                        !Files.isRegularFile(root.resolve("src/main/resources/data/minecraft/worldgen/noise_settings/overworld.json"))) throw new IllegalStateException("Regeneration removed integration files");
                    workspace.getFileManager().saveWorkspaceDirectlyAndWait();
                    workspace.close();
                    Files.writeString(root.resolve("terrain-test-success"), "Workspace created; terrain survived regeneration.\n");
                } catch (Throwable error) {
                    error.printStackTrace();
                    try { Files.writeString(Path.of(System.getenv("TERRAIN_TEST_WORKSPACE"), "terrain-test-failed"), error.toString()); } catch (Exception ignored) {}
                }
            }, "TerrainStudioWorkspaceTest");
            thread.start();
        });
    }
}
